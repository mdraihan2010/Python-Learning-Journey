a = 5
b = 3

print("AND :", a & b) # 0101 & 0011 = 0001 = 1
print("OR  :", a | b) # 0101 | 0011 = 0111 = 7
print("XOR :", a ^ b) # 0101 ^ 0011 = 0110 = 6
print("NOT :", ~a) # ~5 = -(5 + 1) = -6
print("LEFT SHIFT :", a << 1) # 0101 << 1 = 1010 = 10
print("RIGHT SHIFT:", a >> 1) # 0101 >> 1 = 0010 = 2