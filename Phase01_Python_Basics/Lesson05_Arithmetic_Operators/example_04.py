#Area of Triangle
base = 10
height = 5
triangle_area = (base * height) / 2
print("Area of Triangle =", triangle_area)

#Area of Circle
radius = 7
circle_area = 3.14 * radius ** 2
print("Area of Circle =", round(circle_area, 2))

#Area of Rectangle
length = 8
width = 4
rectangle_area = length * width
print("Area of Rectangle =", rectangle_area)

#Area of Square
side = 6
square_area = side ** 2
print("Area of Square =", square_area)

#Area of Trapezoid
base1 = 5
base2 = 7
height = 4
trapezoid_area = ((base1 + base2) * height) / 2
print("Area of Trapezoid =", trapezoid_area)

#Area of Parallelogram
base = 9
height = 6
parallelogram_area = base * height
print("Area of Parallelogram =", parallelogram_area)

